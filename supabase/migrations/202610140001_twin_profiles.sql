  display_name text not null default '' check (char_length(display_name) <= 80),
  date_of_birth date,
  pronouns text check (char_length(pronouns) <= 50),
  city text check (char_length(city) <= 100),
  headline text check (char_length(headline) <= 120),
  bio text check (char_length(bio) <= 2000),
  worldview text check (char_length(worldview) <= 80),
  worldview_description text check (char_length(worldview_description) <= 500),
  children_preference text check (
    children_preference is null or children_preference in
      ('childfree', 'wants_children', 'unsure', 'open_to_discussing', 'prefer_not_to_say')
