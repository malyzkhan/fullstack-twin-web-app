  date_parent_preference text check (
    date_parent_preference is null or date_parent_preference in
      ('yes', 'no', 'open_to_discussing', 'prefer_not_to_say')
  ),
  relationship_intention text check (
    relationship_intention is null or relationship_intention in
      ('long_term', 'casual', 'friendship', 'open_to_see')
  ),
  relationship_structure text check (
    relationship_structure is null or relationship_structure in
      ('monogamy', 'consensual_non_monogamy', 'open_to_discussing', 'prefer_not_to_say')
