create or replace function public.can_view_profile_photo(storage_path text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  target_user_id uuid;
  viewer_id uuid := (select auth.uid());
begin
  if viewer_id is null then
    return false;
  end if;

  begin
    target_user_id := split_part(storage_path, '/', 1)::uuid;
  exception when invalid_text_representation then
    return false;
  end;

  if target_user_id = viewer_id then
    return true;
  end if;

  return exists (
    select 1
    from public.profiles p
    where p.id = target_user_id
      and p.profile_status = 'active'
      and p.is_discoverable
      and exists (
        select 1
        from public.profile_visibility visibility
        where visibility.user_id = target_user_id
          and visibility.field_name = 'photos'
          and visibility.visibility = 'public'
      )
      and exists (
        select 1
        from public.profile_photos photo
        where photo.user_id = target_user_id
          and photo.storage_path = $1
      )
  ) and not exists (
    select 1
    from public.blocked_users b
    where (b.blocker_id = viewer_id and b.blocked_user_id = target_user_id)
       or (b.blocker_id = target_user_id and b.blocked_user_id = viewer_id)
  );
end;
$$;

revoke all on function public.can_view_profile_photo(text) from public, anon;
grant execute on function public.can_view_profile_photo(text) to authenticated;

create or replace function public.reorder_profile_photos(photo_ids uuid[])
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  photo_count integer;
  distinct_count integer;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication required.' using errcode = '42501';
  end if;

  select count(*)
  into photo_count
  from public.profile_photos
  where user_id = (select auth.uid());

  select count(distinct requested.id)
  into distinct_count
  from unnest(photo_ids) requested(id);

  if coalesce(array_length(photo_ids, 1), 0) <> photo_count
    or coalesce(array_length(photo_ids, 1), 0) <> distinct_count
    or exists (
      select 1
      from unnest(photo_ids) requested(id)
      left join public.profile_photos owned
        on owned.id = requested.id
       and owned.user_id = (select auth.uid())
      where owned.id is null
    ) then
    raise exception 'Photo order must contain every owned photo exactly once.'
      using errcode = 'check_violation';
  end if;

  update public.profile_photos photo
  set display_order = requested.position::smallint
  from unnest(photo_ids) with ordinality requested(id, position)
  where photo.id = requested.id
    and photo.user_id = (select auth.uid());
end;
$$;

create or replace function public.set_primary_profile_photo(photo_id uuid)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication required.' using errcode = '42501';
  end if;

  if not exists (
    select 1 from public.profile_photos
    where id = photo_id and user_id = (select auth.uid())
  ) then
    raise exception 'Photo not found.' using errcode = 'P0002';
  end if;

  update public.profile_photos
  set is_primary = false
  where user_id = (select auth.uid()) and is_primary;

  update public.profile_photos
  set is_primary = true
  where id = photo_id and user_id = (select auth.uid());
end;
$$;

create or replace function public.replace_profile_interests(
  selected_interest_ids bigint[],
  custom_interest_names text[]
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  current_user_id uuid := (select auth.uid());
  interest_id bigint;
  interest_name text;
  next_order smallint := 0;
begin
  if current_user_id is null then
    raise exception 'Authentication required.' using errcode = '42501';
  end if;

  if coalesce(array_length(selected_interest_ids, 1), 0) +
     coalesce(array_length(custom_interest_names, 1), 0) > 20 then
    raise exception 'Choose no more than 20 interests.' using errcode = 'check_violation';
  end if;

  if (
    select count(distinct selected_id)
    from unnest(selected_interest_ids) selected_id
  ) <> coalesce(array_length(selected_interest_ids, 1), 0) then
    raise exception 'An interest was selected more than once.' using errcode = 'check_violation';
  end if;

  if exists (
    select 1
    from unnest(custom_interest_names) custom_name
    where nullif(btrim(custom_name), '') is null
       or char_length(btrim(custom_name)) > 40
  ) or (
    select count(distinct lower(btrim(custom_name)))
    from unnest(custom_interest_names) custom_name
  ) <> coalesce(array_length(custom_interest_names, 1), 0) then
    raise exception 'Custom interests must be unique and no longer than 40 characters.'
      using errcode = 'check_violation';
  end if;

  if exists (
    select 1
    from unnest(selected_interest_ids) selected_id
    left join public.interests i on i.id = selected_id
    where i.id is null
  ) then
    raise exception 'An interest selection is not available.' using errcode = 'check_violation';
  end if;

  delete from public.profile_interests where user_id = current_user_id;

  foreach interest_id in array coalesce(selected_interest_ids, '{}'::bigint[]) loop
    insert into public.profile_interests (user_id, interest_id, display_order)
    values (current_user_id, interest_id, next_order);
    next_order := next_order + 1;
  end loop;

  foreach interest_name in array coalesce(custom_interest_names, '{}'::text[]) loop
    insert into public.profile_interests (user_id, custom_name, display_order)
    values (current_user_id, btrim(interest_name), next_order);
    next_order := next_order + 1;
  end loop;
end;
$$;

create or replace function public.reorder_profile_interests(interest_ids uuid[])
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  owned_count integer;
  requested_count integer;
  distinct_count integer;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication required.' using errcode = '42501';
  end if;

  select count(*) into owned_count
  from public.profile_interests
  where user_id = (select auth.uid());

  select count(*), count(distinct requested.id)
  into requested_count, distinct_count
  from unnest(interest_ids) requested(id);

  if requested_count <> owned_count or distinct_count <> requested_count
    or exists (
      select 1
      from unnest(interest_ids) requested(id)
      left join public.profile_interests owned
        on owned.id = requested.id
       and owned.user_id = (select auth.uid())
      where owned.id is null
    ) then
    raise exception 'Interest order must contain every owned interest exactly once.'
      using errcode = 'check_violation';
  end if;

  update public.profile_interests item
  set display_order = requested.position::smallint
  from unnest(interest_ids) with ordinality requested(id, position)
  where item.id = requested.id
    and item.user_id = (select auth.uid());
end;
$$;

