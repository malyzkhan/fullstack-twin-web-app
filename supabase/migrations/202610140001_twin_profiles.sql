create or replace function public.get_public_profile(target_user_id uuid)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'display_name', p.display_name,
    'age', case
      when ((select auth.uid()) = p.id or coalesce(v.visibility, 'private') = 'public')
        and p.date_of_birth is not null
      then date_part('year', age(current_date, p.date_of_birth))::integer
      else null
    end,
    'pronouns', case when (select auth.uid()) = p.id or v_pronouns.visibility = 'public' then p.pronouns end,
    'city', case when (select auth.uid()) = p.id or v_city.visibility = 'public' then p.city end,
    'headline', case when (select auth.uid()) = p.id or v_headline.visibility = 'public' then p.headline end,
    'bio', case when (select auth.uid()) = p.id or v_bio.visibility = 'public' then p.bio end,
    'worldview', case when (select auth.uid()) = p.id or v_worldview.visibility = 'public' then p.worldview end,
    'worldview_description', case when (select auth.uid()) = p.id or v_worldview_description.visibility = 'public' then p.worldview_description end,
    'children_preference', case when (select auth.uid()) = p.id or v_children.visibility = 'public' then p.children_preference end,
    'date_parent_preference', case when (select auth.uid()) = p.id or v_date_parent.visibility = 'public' then p.date_parent_preference end,
    'relationship_intention', case when (select auth.uid()) = p.id or v_intention.visibility = 'public' then p.relationship_intention end,
    'relationship_structure', case when (select auth.uid()) = p.id or v_structure.visibility = 'public' then p.relationship_structure end,
    'personality_type', case when (select auth.uid()) = p.id or v_personality.visibility = 'public' then p.personality_type end,
    'prompts', case when (select auth.uid()) = p.id or v_prompts.visibility = 'public' then p.profile_prompts else '{}'::jsonb end,
    'interests', case when (select auth.uid()) = p.id or v_interests.visibility = 'public' then (
      select coalesce(jsonb_agg(jsonb_build_object(
        'name', coalesce(i.name, pi.custom_name),
        'category', i.category,
        'display_order', pi.display_order
      ) order by pi.display_order), '[]'::jsonb)
      from public.profile_interests pi
      left join public.interests i on i.id = pi.interest_id
      where pi.user_id = p.id
    ) else '[]'::jsonb end,
    'photos', case when (select auth.uid()) = p.id or v_photos.visibility = 'public' then (
      select coalesce(jsonb_agg(jsonb_build_object(
        'storage_path', ph.storage_path,
        'display_order', ph.display_order,
        'is_primary', ph.is_primary
      ) order by ph.display_order), '[]'::jsonb)
      from public.profile_photos ph
      where ph.user_id = p.id
    ) else '[]'::jsonb end
  )
  from public.profiles p
  left join public.profile_visibility v on v.user_id = p.id and v.field_name = 'age'
  left join public.profile_visibility v_pronouns on v_pronouns.user_id = p.id and v_pronouns.field_name = 'pronouns'
  left join public.profile_visibility v_city on v_city.user_id = p.id and v_city.field_name = 'city'
  left join public.profile_visibility v_headline on v_headline.user_id = p.id and v_headline.field_name = 'headline'
  left join public.profile_visibility v_bio on v_bio.user_id = p.id and v_bio.field_name = 'bio'
  left join public.profile_visibility v_worldview on v_worldview.user_id = p.id and v_worldview.field_name = 'worldview'
  left join public.profile_visibility v_worldview_description on v_worldview_description.user_id = p.id and v_worldview_description.field_name = 'worldview_description'
  left join public.profile_visibility v_children on v_children.user_id = p.id and v_children.field_name = 'children_preference'
  left join public.profile_visibility v_date_parent on v_date_parent.user_id = p.id and v_date_parent.field_name = 'date_parent_preference'
  left join public.profile_visibility v_intention on v_intention.user_id = p.id and v_intention.field_name = 'relationship_intention'
  left join public.profile_visibility v_structure on v_structure.user_id = p.id and v_structure.field_name = 'relationship_structure'
  left join public.profile_visibility v_personality on v_personality.user_id = p.id and v_personality.field_name = 'personality_type'
  left join public.profile_visibility v_prompts on v_prompts.user_id = p.id and v_prompts.field_name = 'prompts'
  left join public.profile_visibility v_interests on v_interests.user_id = p.id and v_interests.field_name = 'interests'
  left join public.profile_visibility v_photos on v_photos.user_id = p.id and v_photos.field_name = 'photos'
  where p.id = target_user_id
    and (select auth.uid()) is not null
    and (
      p.id = (select auth.uid())
      or (
        p.profile_status = 'active'
        and p.is_discoverable
        and not exists (
          select 1 from public.blocked_users b
          where (b.blocker_id = (select auth.uid()) and b.blocked_user_id = p.id)
             or (b.blocker_id = p.id and b.blocked_user_id = (select auth.uid()))
        )
      )
    );
$$;

