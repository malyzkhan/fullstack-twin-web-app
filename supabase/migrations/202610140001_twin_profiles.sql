create or replace function public.enforce_profile_age()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.profile_status = 'active' then
    if not exists (
      select 1
      from auth.users u
      where u.id = new.id
        and u.email_confirmed_at is not null
    ) then
      raise exception 'Verify your email before activating a dating profile.'
        using errcode = '42501';
    end if;

    if nullif(btrim(new.display_name), '') is null
      or new.date_of_birth is null
      or new.date_of_birth > current_date
      or new.date_of_birth > (current_date - interval '18 years')::date then
      raise exception 'An active dating profile requires a date of birth showing the user is at least 18 years old.'
        using errcode = 'check_violation';
    end if;
  end if;

  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists profiles_enforce_age on public.profiles;
create trigger profiles_enforce_age
  before insert or update on public.profiles
  for each row execute function public.enforce_profile_age();

create or replace function public.provision_twin_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  initial_name text;
  visible_field text;
begin
  initial_name := coalesce(
    nullif(btrim(new.raw_user_meta_data ->> 'full_name'), ''),
    nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
    ''
  );

  insert into public.profiles (id, display_name)
  values (new.id, left(initial_name, 80))
  on conflict (id) do nothing;

  insert into public.user_preferences (user_id)
  values (new.id)
  on conflict (user_id) do nothing;

  insert into public.user_settings (user_id)
  values (new.id)
  on conflict (user_id) do nothing;

  foreach visible_field in array array['age', 'photos'] loop
    insert into public.profile_visibility (user_id, field_name, visibility)
    values (new.id, visible_field, 'public')
    on conflict (user_id, field_name) do nothing;
  end loop;

  return new;
end;
$$;

